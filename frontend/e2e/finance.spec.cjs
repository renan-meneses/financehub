const { test, expect } = require('@playwright/test');
const { randomUUID, randomBytes } = require('node:crypto');

test('create categories and bills, pay once, cancel pending bills and inspect financial analysis', async ({ page, request, baseURL }) => {
  const email = `financehub-${randomUUID()}@example.test`;
  const password = randomBytes(24).toString('base64url');
  const workspaceName = `Synthetic workspace ${randomUUID().slice(0, 8)}`;
  const mailpit = process.env.E2E_MAILPIT_URL || 'http://localhost:8025';
  const browserErrors = [];
  page.on('pageerror', error => browserErrors.push(error.message));
  await page.goto('/#!/register');
  await page.getByLabel('Nome', { exact: true }).fill('Synthetic test user');
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Confira seu e-mail');

  let messageId;
  await expect.poll(async () => {
    const response = await request.get(`${mailpit}/api/v1/search`, { params: { query: `to:${email}` } });
    expect(response.ok()).toBeTruthy();
    const messages = (await response.json()).messages;
    messageId = messages[0]?.ID;
    return Boolean(messageId);
  }, { timeout: 40000 }).toBe(true);
  const message = await request.get(`${mailpit}/api/v1/message/${encodeURIComponent(messageId)}`);
  expect(message.ok()).toBeTruthy();
  const link = (await message.json()).Text.match(/https?:\/\/[^\s]+/)[0];
  expect(new URL(link).origin).toBe(new URL(baseURL).origin);
  await page.goto(link);
  await page.getByRole('button', { name: 'Confirmar e-mail' }).click();
  await expect(page.getByRole('status')).toContainText('E-mail confirmado');
  await page.getByRole('link', { name: 'Voltar ao login' }).click();
  const signIn = page.getByRole('button', { name: 'Entrar', exact: true });
  await expect(signIn).toBeDisabled();
  await page.getByLabel('E-mail', { exact: true }).fill(email);
  await page.getByLabel('E-mail', { exact: true }).press('Tab');
  await expect(page.getByLabel('Senha', { exact: true })).toBeFocused();
  await page.keyboard.type('incorrect-synthetic-password');
  await page.keyboard.press('Tab');
  await expect(signIn).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('alert')).toContainText('Acesso inválido ou expirado');
  await expect(page.getByLabel('Senha', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue(email);
  await expect(signIn).toBeDisabled();
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByLabel('Senha', { exact: true }).press('Enter');
  await expect(page.getByRole('heading', { name: 'Seus workspaces' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Seus workspaces' })).toBeVisible();
  await page.getByLabel('Nome do workspace').fill(workspaceName);
  await page.getByRole('button', { name: 'Criar', exact: true }).click();
  await page.locator('.workspace-card').filter({ hasText: workspaceName }).getByRole('button').click();
  await expect(page.getByRole('heading', { name: 'Contas financeiras' })).toBeVisible();
  await page.getByLabel('Nome da conta').fill('Analysis account');
  await page.getByLabel('Saldo de abertura', { exact: true }).fill('1000.00');
  await page.getByLabel('Data de abertura', { exact: true }).fill('2020-01-01');
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
  await expect(page.locator('.workspace-card')).toContainText('1.000,00 BRL');
  await page.getByRole('link', { name: 'Categorias', exact: true }).click();
  await page.getByLabel('Nome da categoria').fill('Alimentação');
  await page.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(page.locator('.workspace-card')).toContainText('Alimentação');
  await page.getByRole('link', { name: 'Débitos', exact: true }).click();
  await page.getByLabel('Descrição', { exact: true }).fill('Compra de mercado');
  await page.getByLabel('Nome da conta').selectOption({ label: 'Analysis account · BRL' });
  await page.getByLabel('Nome da categoria').selectOption({ label: 'Alimentação' });
  await page.getByLabel('Valor', { exact: true }).fill('150.25');
  await page.getByRole('button', { name: 'Cadastrar débito', exact: true }).click();
  const bill = page.locator('.workspace-card').filter({ hasText: 'Compra de mercado' });
  await expect(bill).toContainText('Pendente');
  await bill.getByRole('button', { name: 'Registrar pagamento' }).click();
  await page.getByRole('button', { name: 'Confirmar pagamento', exact: true }).click();
  await expect(bill).toContainText('Pago');
  await expect(bill.getByRole('button', { name: 'Registrar pagamento' })).toHaveCount(0);
  await page.getByLabel('Descrição', { exact: true }).fill('Cancelar esta conta');
  await page.getByLabel('Valor', { exact: true }).fill('25.00');
  await page.getByRole('button', { name: 'Cadastrar débito', exact: true }).click();
  const cancelled = page.locator('.workspace-card').filter({ hasText: 'Cancelar esta conta' });
  await cancelled.getByRole('button', { name: 'Cancelar débito' }).click();
  await page.getByRole('button', { name: 'Confirmar cancelamento' }).click();
  await expect(cancelled).toContainText('Cancelado');
  await page.getByRole('link', { name: 'Análise financeira', exact: true }).click();
  await expect(page.locator('.finance-metrics')).toContainText('849,75 BRL');
  await expect(page.locator('.category-bar')).toContainText('150,25 BRL');
  await expect(page.locator('meter')).toHaveAttribute('value', '100.00');
  await expect(page.getByRole('table')).toContainText('150,25 BRL');
  await page.getByLabel('Idioma', { exact: true }).selectOption('en');
  await expect(page.getByRole('heading', { name: 'Financial analysis', exact: true })).toBeVisible();
  await page.locator('#language').selectOption('pt-BR');
  await page.getByRole('button', { name: 'Alternar tema' }).click();
  await expect(page.locator('body')).toHaveClass(/dark-theme/);
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.screenshot({ path: '/tmp/financehub-analysis-' + test.info().project.name + '.png', fullPage: true });
  await page.getByRole('link', { name: 'Contas financeiras', exact: true }).click();
  await page.getByRole('button', { name: 'Histórico', exact: true }).click();
  await expect(page.getByRole('table')).toContainText('Pagamento de débito');
  await expect(page.getByRole('table')).toContainText('-150,25 BRL');
  expect(browserErrors).toEqual([]);
});
